"""Сборка tasks.json и split_tasks.json домена banking_ru (срез из 10 задач).

Стандарт этапа 1 плана «50 сложных задач»:
- клиент НЕ знает внутренний customer_id: идентификация через find_customer
  (телефон) + verify_identity (кодовое слово, которое агент обязан спросить);
- критичные числа проверяются состоянием БД, communicate_info — статусы,
  даты и маркеры отказов;
- в описаниях инструментов нет правил политики — только в policy.md.
"""
import json
from pathlib import Path

DATA = Path(__file__).resolve().parents[2] / "data/tau2/domains/banking_ru"
DOMAIN = "banking_ru"
tasks = []
_counters = {}


def act(name, requestor="assistant", **arguments):
    n = _counters.get(name, 0)
    _counters[name] = n + 1
    return dict(action_id=f"{name}_{n}", requestor=requestor, name=name,
                arguments=arguments)


def ident(phone, customer_id, code_word):
    """Стандартное начало эталонной траектории: поиск + подтверждение."""
    return [act("find_customer", phone=phone),
            act("verify_identity", customer_id=customer_id, credential=code_word)]


def env_assert(func_name, assert_value=True, **arguments):
    return dict(env_type="assistant", func_name=func_name, arguments=arguments,
                assert_value=assert_value)


def task(tid, purpose, policies, notes, persona, reason, known, unknown,
         instructions, actions, communicate, asserts=None, nl=None):
    basis = ["DB", "COMMUNICATE"]
    if asserts:
        basis.append("ENV_ASSERTION")
    tasks.append(dict(
        id=tid,
        description=dict(purpose=purpose, relevant_policies=policies, notes=notes),
        user_scenario=dict(persona=persona, instructions=dict(
            domain=DOMAIN, reason_for_call=reason, known_info=known,
            unknown_info=unknown, task_instructions=instructions)),
        initial_state=None,
        evaluation_criteria=dict(
            actions=actions, env_assertions=asserts, communicate_info=communicate,
            nl_assertions=nl, reward_basis=basis),
    ))


