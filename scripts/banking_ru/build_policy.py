# -*- coding: utf-8 -*-
"""Сборка policy_solo.md из policy.md.

Эталонные домены (telecom) держат для одиночного режима отдельный файл
политики: без собеседника часть правил диалоговой инструкции теряет смысл или
прямо противоречит среде. Два файла руками разъезжаются, поэтому solo-версия
собирается из основной заменой размеченных мест — расхождение между ними
проверяется тестом.
"""
from pathlib import Path

DATA = Path(__file__).resolve().parents[2] / "data/tau2/domains/banking_ru"
SRC = DATA / "policy.md"
OUT = DATA / "policy_solo.md"

# (что заменить, на что) — каждое место объяснено в комментарии
REPLACEMENTS = [
    # Роль: вместо чата — работа с письменным обращением.
    ("""Вы — агент поддержки клиентов банка в чате мобильного приложения. Вы общаетесь
с клиентом на русском языке и выполняете операции только через доступные вам
инструменты.""",
     """Вы — агент поддержки клиентов банка. Вы разбираете письменное обращение
клиента (тикет) и выполняете операции только через доступные вам инструменты.
Живого диалога нет: вы не пишете клиенту сообщений и не получаете их.

- Всё, что знает клиент и чего нет в системе, спрашивайте инструментом
  `ask_client`: кодовое слово, код из СМС, реквизиты, обстоятельства операции.
  Клиент отвечает только на вопросы по делу и своих внутренних
  идентификаторов не знает.
- **Работа по обращению заканчивается ответом клиенту.** Когда все операции
  выполнены, отправьте итог инструментом `reply_to_ticket`: что сделано, какие
  суммы и даты получились, что выполнить нельзя и почему. Без ответа обращение
  считается необработанным, даже если все операции проведены верно. Ответ
  отправляется один раз и в самом конце.
- Делайте по одному вызову инструмента за раз."""),
    # Подтверждение операции: в тикете его берут из текста обращения или
    # спрашивают у клиента, а не «дожидаются» реплики.
    ("""- Прежде чем выполнить операцию, которая меняет деньги клиента, назовите её
  итоговую сумму и дождитесь подтверждения клиента.""",
     """- Операцию, которая меняет деньги клиента, выполняйте только если клиент
  согласился на неё в обращении либо подтвердил её через `ask_client`.
  Итоговую сумму назовите в ответе по обращению."""),
]


def build() -> str:
    text = SRC.read_text(encoding="utf-8")
    for old, new in REPLACEMENTS:
        if text.count(old) != 1:
            raise SystemExit(
                f"policy.md изменилась: заменяемый фрагмент встречается "
                f"{text.count(old)} раз — {old[:60]!r}"
            )
        text = text.replace(old, new)
    return text


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"policy_solo.md: {len(build().splitlines())} строк")
